// دالة ترجمة الاسم
export const translateEmployeeName = (englishName) => {
  if (!englishName) return '';
  
  // تنظيف النص
  const cleanName = englishName.trim();
  
  // البحث عن الترجمة الكاملة
  if (employeeNameTranslations[cleanName]) {
    return employeeNameTranslations[cleanName];
  }
  
  // البحث عن أجزاء من الاسم
  const nameParts = cleanName.split(' ');
  const translatedParts = nameParts.map(part => {
    // البحث عن الترجمة
    if (employeeNameTranslations[part]) {
      return employeeNameTranslations[part];
    }
    
    // إذا لم توجد ترجمة، إرجاع النص الأصلي
    return part;
  });
  
  return translatedParts.join(' ');
};

// دالة ترجمة اسم القسم
export const translateDepartment = (englishDepartment) => {
  if (!englishDepartment) return '';
  
  const cleanDept = englishDepartment.trim();
  
  // البحث عن الترجمة
  if (employeeNameTranslations[cleanDept]) {
    return employeeNameTranslations[cleanDept];
  }
  
  // ترجمات إضافية للأقسام
  const departmentTranslations = {
    'IT': 'تقنية المعلومات',
    'HR': 'الموارد البشرية',
    'Admin': 'الإدارة',
    'Support': 'الدعم الفني',
    'Production': 'الإنتاج',
    'Maintenance': 'الصيانة',
    'Security': 'الأمن',
    'Transport': 'النقل',
    'Warehouse': 'المستودع',
    'Quality': 'الجودة'
  };
  
  if (departmentTranslations[cleanDept]) {
    return departmentTranslations[cleanDept];
  }
  
  return cleanDept;
};

// دالة ترجمة كاملة لبيانات الموظف
export const translateEmployeeData = (employee) => {
  if (!employee) return employee;
  
  return {
    ...employee,
    'Name': translateEmployeeName(employee['Name']),
    'department': translateDepartment(employee['department']),
    'job_title': translateEmployeeName(employee['job_title'])
  };
};

// دالة ترجمة قائمة الموظفين
export const translateEmployeesList = (employees) => {
  if (!Array.isArray(employees)) return employees;
  
  return employees.map(employee => translateEmployeeData(employee));
};
